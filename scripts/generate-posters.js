const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'assets', 'posters');
const files = fs.existsSync(dir)
  ? fs.readdirSync(dir).filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
  : [];

const lines = files.map((f) => {
  const name = f.replace(/\.[^.]+$/, '');
  return `  '${name}': require('../assets/posters/${f}'),`;
});

const output = `// AUTO-GENERATED by scripts/generate-posters.js. Do not edit by hand.
export const POSTERS = {
${lines.join('\n')}
};

export function slugify(title) {
  return title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
}

export function getPoster(title) {
  return POSTERS[slugify(title)] || null;
}
`;

fs.writeFileSync(path.join(__dirname, '..', 'src', 'posters.js'), output);
console.log(`Registered ${files.length} posters.`);